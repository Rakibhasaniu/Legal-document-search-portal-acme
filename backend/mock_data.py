def search_documents(query: str):
    """
    Mock search function that searches through legal documents
    Returns documents that contain the query terms
    """
    query_lower = query.lower()
    query_terms = query_lower.split()

    results = []

    for doc in LEGAL_DOCUMENTS:
        content_lower = doc["content"].lower()
        title_lower = doc["title"].lower()
        category_lower = doc["category"].lower()

        relevance_score = 0
        matched_terms = []

        for term in query_terms:
            if term in content_lower:
                relevance_score += content_lower.count(term)
                matched_terms.append(term)
            if term in title_lower:
                relevance_score += 10  
                if term not in matched_terms:
                    matched_terms.append(term)
            if term in category_lower:
                relevance_score += 5  
                if term not in matched_terms:
                    matched_terms.append(term)

        if relevance_score > 0:
            excerpts = extract_excerpts(doc["content"], query_terms)

            results.append({
                "document_id": doc["id"],
                "title": doc["title"],
                "category": doc["category"],
                "relevance_score": relevance_score,
                "matched_terms": matched_terms,
                "excerpts": excerpts,
                "effective_date": doc["effective_date"],
                "jurisdiction": doc["jurisdiction"]
            })

    results.sort(key=lambda x: x["relevance_score"], reverse=True)

    return results


def extract_excerpts(content: str, query_terms: list, context_chars: int = 200):
    """
    Extract relevant excerpts from document content based on query terms
    """
    content_lower = content.lower()
    excerpts = []
    seen_positions = set()

    for term in query_terms:
        term_lower = term.lower()
        start = 0

        while True:
            pos = content_lower.find(term_lower, start)
            if pos == -1:
                break

            if any(abs(pos - seen_pos) < context_chars for seen_pos in seen_positions):
                start = pos + 1
                continue

            excerpt_start = max(0, pos - context_chars // 2)
            excerpt_end = min(len(content), pos + len(term) + context_chars // 2)

            excerpt = content[excerpt_start:excerpt_end].strip()

            if excerpt_start > 0:
                excerpt = "..." + excerpt
            if excerpt_end < len(content):
                excerpt = excerpt + "..."

            excerpts.append(excerpt)
            seen_positions.add(pos)
            start = pos + 1

            if len([e for e in excerpts]) >= 2:
                break

    return excerpts[:5]  


def generate_summary(query: str, results: list):
    """
    Generate a summary of search results
    """
    if not results:
        return "No relevant legal documents found for your query."

    summary_parts = [
        f"Found {len(results)} relevant legal document(s) for your query: '{query}'",
        ""
    ]

    for i, result in enumerate(results[:3], 1):  
        summary_parts.append(
            f"{i}. {result['title']} ({result['category']}): "
            f"Contains {len(result['matched_terms'])} matching term(s). "
            f"Jurisdiction: {result['jurisdiction']}"
        )

    return "\n".join(summary_parts)
